/*
 * STM32F072 / APM32F072 uses QMK's software WS2812 bitbang driver at 48 MHz.
 * Default WS2812_T0H (350 ns) evaluates to NS_TO_CYCLES(350) = 1.12, causing
 * modern GCC (-Os) to emit a 2-iteration loop (~650 ns) that WS2812 latches
 * as '1' bits (turning all LEDs pure white). 250 ns compiles to a single
 * unrolled 6-NOP block (~270 ns), centered in the 220-380 ns T0H spec.
 */
#define WS2812_T0H 250

